const DICTIONARIES = Object.freeze({ en: Object.freeze(en), 'zh-tw': Object.freeze(zhTw), 'zh-cn': Object.freeze(zhCn) });

function normalizeLocale(locale) {
  const value = String(locale || '').trim().toLowerCase().replace(/_/g, '-');
  if (value.startsWith('zh-hant') || value.startsWith('zh-tw') || value.startsWith('zh-hk') || value.startsWith('zh-mo')) return 'zh-tw';
  if (value.startsWith('zh-hans') || value.startsWith('zh-cn') || value.startsWith('zh-sg')) return 'zh-cn';
  if (value.startsWith('en')) return 'en';
  return 'en';
}

function resolveLanguage(configured, vscodeLocale) {
  const value = String(configured || 'auto').toLowerCase();
  if (SUPPORTED_LANGUAGES.includes(value)) return value;
  return normalizeLocale(vscodeLocale);
}

function getMessages(language) {
  return DICTIONARIES[SUPPORTED_LANGUAGES.includes(language) ? language : 'en'];
}

function interpolate(template, vars = {}) {
  return String(template).replace(/\{([A-Za-z0-9_]+)\}/g, (match, key) => Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match);
}

function t(language, key, vars) {
  const messages = getMessages(language);
  return interpolate(messages[key] ?? DICTIONARIES.en[key] ?? key, vars);
}

function translateValidationMessage(language, message) {
  const exact = {
    'Card must be a JSON object.': 'validation.issue.cardObject',
    'Must equal "chara_card_v3".': 'validation.issue.mustEqualSpec',
    'Must be a string.': 'validation.issue.mustString',
    'Must be an object.': 'validation.issue.mustObject',
    'Must be an array of strings.': 'validation.issue.arrayStrings',
    'CCv3 requires an array of strings.': 'validation.issue.ccv3ArrayStrings',
    'Must be a non-negative Unix timestamp in seconds.': 'validation.issue.nonNegativeTimestamp',
    'Must be an array.': 'validation.issue.mustArray',
    'Should be a lowercase extension without a leading dot.': 'validation.issue.lowercaseExt',
    'When multiple icon assets exist, exactly one must be named "main".': 'validation.issue.iconMain',
    'At most one background asset may be named "main".': 'validation.issue.backgroundMain',
    'Must be a boolean.': 'validation.issue.mustBoolean',
    'Must be a number.': 'validation.issue.mustNumber',
    'CCv3 requires a boolean.': 'validation.issue.ccv3Boolean',
    'Must be a boolean when present.': 'validation.issue.booleanPresent'
  };
  if (exact[message]) return t(language, exact[message]);
  const version = /^Editor targets CCv3 3\.0; imported value is (.+)\.$/.exec(message);
  if (version) return t(language, 'validation.issue.versionMismatch', { value: version[1] });
  const regex = /^Invalid regex: (.*)$/.exec(message);
  if (regex) return t(language, 'validation.issue.invalidRegex', { detail: regex[1] });
  return message;
}

